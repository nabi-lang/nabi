/// A Microsoft intrinsic clang has as a builtin.
pub(crate) fn ms_builtin(name: &str) -> bool {
    const PREFIXES: &[&str] = &[
        "_Interlocked",
        "_BitScan",
        "_bittest",
        "__iso_volatile_",
        "__readgs",
        "__readfs",
        "__writegs",
        "__writefs",
        "__readx18",
        "__writex18",
        "__addx18",
        "__incx18",
        "_byteswap_",
        "_rotl",
        "_rotr",
        "__lzcnt",
        "__popcnt",
        "_Copy",
        "_Count",
        "__shift",
    ];
    const NAMES: &[&str] = &[
        "__noop",
        "__debugbreak",
        "__fastfail",
        "__assume",
        "__annotation",
        "_alloca",
        "_ReturnAddress",
        "_AddressOfReturnAddress",
        "__getReg",
        "__mulh",
        "__umulh",
        "_mul128",
        "_umul128",
        "__cpuid",
        "__cpuidex",
        "__dmb",
        "__dsb",
        "__isb",
        "__yield",
        "__wfe",
        "__wfi",
        "__sev",
        "__sevl",
        "__prefetch",
        "_ReadWriteBarrier",
        "_ReadBarrier",
        "_WriteBarrier",
        "__faststorefence",
        "_mm_pause",
    ];
    PREFIXES.iter().any(|p| name.starts_with(p)) || NAMES.contains(&name)
}

