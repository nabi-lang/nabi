//! `__has_*` queries and their feature tables.

#[allow(clippy::wildcard_imports)]
use crate::*;

impl Pp<'_> {
    /// `__has_feature(x)` and its kin.
    pub(crate) fn query(&mut self, t: Tok) -> Result<i64, Error> {
        let name = self.spell(t).to_owned();
        if name == "__has_include" || name == "__has_include_next" {
            return Err(self.err(t.loc, &format!("'{name}' is only allowed in #if and #elif")));
        }
        let args = self.paren_args(t)?;
        let arg = self.join(&args);
        let word = arg.trim_matches('_').replace(' ', "");
        let ms = self.target.msvc;
        Ok(match name.as_str() {
            "__has_attribute" => i64::from(ATTRIBUTES.contains(&word.as_str())),
            "__has_declspec_attribute" => i64::from(ms && DECLSPECS.contains(&arg.as_str())),
            "__has_builtin" | "__has_constexpr_builtin" => i64::from(
                arg.starts_with("__builtin_")
                    || arg.starts_with("__sync_")
                    || arg.starts_with("__atomic_")
                    || arg.starts_with("__c11_atomic_")
                    || arg.starts_with("__is_target_")
                    || matches!(arg.as_str(), "__has_builtin" | "__make_integer_seq")
                    || (ms && ms_builtin(&arg)),
            ),
            "__has_feature" | "__has_extension" => {
                let darwin = self.target.os == Os::Darwin;
                i64::from(
                    FEATURES.contains(&arg.as_str())
                        || (darwin && arg == "blocks")
                        || (self.target.objc && OBJC_FEATURES.contains(&arg.as_str()))
                        || (darwin
                            && name == "__has_extension"
                            && arg == "define_target_os_macros")
                        || (name == "__has_extension" && EXTENSIONS.contains(&arg.as_str())),
                )
            }
            "__has_warning" => 1,
            "__is_identifier" => i64::from(args.len() == 1 && !is_keyword(args[0].sym, ms)),
            "__is_target_arch" => i64::from(self.target_arch_is(&arg)),
            "__is_target_vendor" => i64::from(match self.target.os {
                Os::Darwin => arg == "apple",
                Os::Windows => arg == "pc",
                _ => arg == "unknown",
            }),
            "__is_target_os" => i64::from(match self.target.os {
                Os::Darwin if self.target.ios => matches!(arg.as_str(), "ios" | "darwin"),
                Os::Darwin => matches!(arg.as_str(), "macos" | "macosx" | "darwin"),
                Os::Linux => arg == "linux",
                Os::Windows => arg == "windows" || arg == "win32",
                Os::FreeBsd => arg == "freebsd",
                Os::Wasi => arg == "wasi",
                Os::None => arg == "unknown" || arg == "none",
            }),
            "__is_target_environment" => i64::from(match self.target.os {
                Os::Darwin if self.target.sim => arg == "simulator",
                Os::Windows => arg == "msvc",
                Os::Linux => arg == if self.target.musl { "musl" } else { "gnu" },
                _ => arg == "unknown",
            }),
            _ => 0,
        })
    }

    pub(crate) fn target_arch_is(&self, a: &str) -> bool {
        match self.target.arch {
            Arch::X86_64 => a == "x86_64" || a == "amd64",
            Arch::X86 => matches!(a, "x86" | "i386" | "i686"),
            Arch::Aarch64 => matches!(a, "aarch64" | "arm64"),
            Arch::Arm => a.starts_with("arm") || a.starts_with("thumb"),
            Arch::Riscv64 => a == "riscv64",
            Arch::Riscv32 => a == "riscv32",
            Arch::Ppc64le => a == "ppc64le" || a == "powerpc64le",
            Arch::S390x => a == "s390x",
            Arch::Wasm32 => a == "wasm32",
        }
    }
}

