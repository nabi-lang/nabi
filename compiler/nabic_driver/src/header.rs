//! `--emit=c-header`: a C header for the package's exports, the reverse
//! of bindgen. It declares each `extern "C"` function with an
//! `#[export_name]` defined in the package's own sources, and every
//! `#[repr(C)]` struct, union and `#[repr(iN)]` enum their signatures
//! reach, with the doc comments as C comments.

use crate::CompiledModule;
use nabic_diagnostic::SourceMap;
use nabic_hir::{EnumId, HirFunction, HirModule, HirStructDef, HirTy, StructId};
use nabic_ir_common::{Abi, Linkage, PrimTy};
use std::fmt::Write;
use std::path::{Path, PathBuf};

/// The header text for `module`.
#[must_use]
pub fn write(module: &CompiledModule, sources: &SourceMap) -> String {
    let hir = &module.hir;
    let own = own_dir(&module.path);
    let mut g = Gen {
        hir,
        sources,
        structs: Vec::new(),
        enums: Vec::new(),
        out: String::new(),
        system: false,
    };
    let mut fns: Vec<&HirFunction> = hir
        .functions
        .iter()
        .filter(|f| {
            f.facts.export_name.is_some()
                && matches!(f.facts.abi, Abi::C { .. })
                && f.facts.linkage != Linkage::Extern
                && f.body.is_some()
                && match &module.mir.link.lib {
                    Some(lib) => nabic_mir::Link::owns(lib, f.facts.path(&f.name)),
                    None => in_dir(sources, f.span.file, own.as_deref()),
                }
        })
        .collect();
    fns.sort_by(|a, b| a.facts.export_name.cmp(&b.facts.export_name));
    fns.dedup_by(|a, b| a.facts.export_name == b.facts.export_name);
    let mut decls = String::new();
    for f in &fns {
        let sym = f.facts.export_name.as_deref().unwrap_or_default();
        match g.function(f, sym) {
            Ok(d) => {
                decls.push_str(&g.doc(f.span));
                decls.push_str(&d);
            }
            Err(why) => {
                let _ = writeln!(decls, "/* skipped {sym}: {why} */");
            }
        }
    }
    let name = module.mir.link.lib.as_deref().unwrap_or(&module.name);
    let guard: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect();
    let mut h = String::new();
    let _ = writeln!(
        h,
        "/* {name}.h: the C interface of Nabi package `{name}`. Generated by nabic \
         --emit=c-header; do not edit. */\n"
    );
    let _ = writeln!(h, "#pragma once\n#ifndef {guard}_H\n#define {guard}_H\n");
    h.push_str("#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n\n");
    if g.system {
        h.push_str(
            "#if defined(_WIN32) && !defined(_WIN64)\n#define NABI_SYSTEM __stdcall\n#else\n\
             #define NABI_SYSTEM\n#endif\n\n",
        );
    }
    h.push_str("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");
    h.push_str(&g.out);
    h.push_str(&decls);
    let _ = write!(
        h,
        "\n#ifdef __cplusplus\n}}\n#endif\n\n#endif /* {guard}_H */\n"
    );
    h
}

/// The directory holding an executable's own sources: `src/` of
/// `src/main.nabi`, a lone file's directory.
fn own_dir(root: &Path) -> Option<PathBuf> {
    let dir = root.parent()?;
    Some(std::fs::canonicalize(dir).unwrap_or_else(|_| dir.to_path_buf()))
}

fn in_dir(sources: &SourceMap, file: u32, dir: Option<&Path>) -> bool {
    let (Some(dir), Some(path)) = (dir, sources.path(file)) else {
        return false;
    };
    let p = Path::new(path);
    let p = std::fs::canonicalize(p).unwrap_or_else(|_| p.to_path_buf());
    p.starts_with(dir)
}

struct Gen<'a> {
    hir: &'a HirModule,
    sources: &'a SourceMap,
    /// Structs written (or being written), in order.
    structs: Vec<StructId>,
    enums: Vec<EnumId>,
    /// Type definitions, each before its first use by value.
    out: String,
    /// An `extern "system"` export: `NABI_SYSTEM` is defined.
    system: bool,
}

impl Gen<'_> {
    fn function(&mut self, f: &HirFunction, sym: &str) -> Result<String, String> {
        let mut params = Vec::new();
        for p in &f.params {
            params.push(self.decl(&p.ty, &p.name, false)?);
        }
        if params.is_empty() {
            params.push("void".to_owned());
        }
        if matches!(f.facts.abi, Abi::C { variadic: true, .. }) {
            params.push("...".to_owned());
        }
        let cc = if matches!(f.facts.abi, Abi::C { system: true, .. }) {
            self.system = true;
            "NABI_SYSTEM "
        } else {
            ""
        };
        let inner = format!("{cc}{sym}({})", params.join(", "));
        let mut d = self.decl(&f.ret_ty, &inner, false)?;
        if f.ret_ty == HirTy::Never {
            d = format!("_Noreturn {d}");
        }
        Ok(format!("{d};\n"))
    }

    /// `ty` declaring `inner` (a name, `*name`, `f(args)`); `konst`: the
    /// innermost type is `const` (behind a `ConstPtr`).
    fn decl(&mut self, ty: &HirTy, inner: &str, konst: bool) -> Result<String, String> {
        let base = |b: &str| {
            let c = if konst { "const " } else { "" };
            if inner.is_empty() {
                format!("{c}{b}")
            } else {
                format!("{c}{b} {inner}")
            }
        };
        match ty {
            HirTy::Unit | HirTy::Never => Ok(base("void")),
            HirTy::Prim(p) => Ok(base(prim(*p))),
            HirTy::Enum(id) => {
                let name = self.enumeration(*id)?;
                Ok(base(&name))
            }
            HirTy::Struct(id) => {
                let s = self.find(*id)?.clone();
                let short = short_name(&s.name);
                match short {
                    "CPtr" | "Ptr" | "ManyPtr" | "ConstPtr" => {
                        let to = s.generic_args.first().ok_or("an untyped pointer")?;
                        let d = self.pointer(to, inner, short == "ConstPtr")?;
                        // `CPtr` may be NULL; a named one says so.
                        let named = !inner.is_empty()
                            && inner.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
                        Ok(if short == "CPtr" && named {
                            format!("{d} /* nullable */")
                        } else {
                            d
                        })
                    }
                    "c_void" => Ok(base("void")),
                    _ if s.repr.transparent && !s.generic_args.is_empty() => {
                        let f = s.fields.first().ok_or("an empty struct")?.ty.clone();
                        self.decl(&f, inner, konst)
                    }
                    _ => {
                        let name = self.structure(*id)?;
                        Ok(base(&name))
                    }
                }
            }
            // `ConstPtr<T> | none`: the same pointer, maybe NULL.
            HirTy::Sum(parts) => match parts.as_slice() {
                [m, HirTy::None] | [HirTy::None, m] => {
                    let d = self.decl(m, inner, konst)?;
                    Ok(format!("{d} /* nullable */"))
                }
                _ => Err("a sum type has no C form".to_owned()),
            },
            HirTy::Array(t, n) => self.decl(t, &format!("{inner}[{n}]"), konst),
            HirTy::Fn(args, ret, b) if b.c_abi => {
                let mut ps = Vec::new();
                for a in args {
                    ps.push(self.decl(a, "", false)?);
                }
                if ps.is_empty() {
                    ps.push("void".to_owned());
                }
                let cc = if b.stdcall {
                    self.system = true;
                    "NABI_SYSTEM "
                } else {
                    ""
                };
                self.decl(ret, &format!("({cc}*{inner})({})", ps.join(", ")), false)
            }
            other => Err(format!("`{other:?}` has no C form")),
        }
    }

    fn pointer(&mut self, to: &HirTy, inner: &str, konst: bool) -> Result<String, String> {
        // A pointer to a function pointer or array needs parentheses.
        let star = if matches!(to, HirTy::Array(..)) {
            format!("(*{inner})")
        } else {
            format!("*{inner}")
        };
        // Pointers to structs need only the forward declaration: no
        // definition is forced before this one.
        if let HirTy::Struct(id) = to {
            let s = self.find(*id)?.clone();
            let plain = !matches!(
                short_name(&s.name),
                "CPtr" | "Ptr" | "ManyPtr" | "ConstPtr" | "c_void"
            );
            if plain && (!s.repr.transparent || s.generic_args.is_empty()) {
                let name = self.structure(*id)?;
                let c = if konst { "const " } else { "" };
                return Ok(format!("{c}{name} {star}"));
            }
        }
        self.decl(to, &star, konst)
    }

    fn find(&self, id: StructId) -> Result<&HirStructDef, String> {
        self.hir
            .structs
            .iter()
            .find(|s| s.id == id)
            .ok_or_else(|| "an unknown struct".to_owned())
    }

    /// The C name of struct `id`, its definition written first.
    fn structure(&mut self, id: StructId) -> Result<String, String> {
        let s = self.find(id)?.clone();
        let name = short_name(&s.name).to_owned();
        if self.structs.contains(&id) {
            return Ok(name);
        }
        if !s.generic_args.is_empty() {
            return Err(format!("`{}` is generic, which C cannot name", s.name));
        }
        self.structs.push(id);
        if s.repr.transparent {
            let f = s.fields.first().ok_or("an empty struct")?;
            let d = self.decl(&f.ty, &name, false)?;
            let doc = self.doc(s.span);
            let _ = writeln!(self.out, "{doc}typedef {d};\n");
            return Ok(name);
        }
        if !s.repr.c && s.union_kind.as_ref().is_none_or(|u| !u.is_repr_c) {
            return Err(format!(
                "`{name}` is not `#[repr(C)]`, so C does not know its layout"
            ));
        }
        let (kw, fields): (&str, Vec<(String, HirTy)>) = match &s.union_kind {
            Some(u) => ("union", u.aliases.clone()),
            None => (
                "struct",
                s.fields
                    .iter()
                    .map(|f| (f.name.clone(), f.ty.clone()))
                    .collect(),
            ),
        };
        let mut body = String::new();
        for (i, (fname, ty)) in fields.iter().enumerate() {
            let d = self.decl(ty, fname, false)?;
            let align = if i == 0 && s.repr.align > 0 {
                format!("_Alignas({}) ", s.repr.align)
            } else {
                String::new()
            };
            let _ = writeln!(body, "    {align}{d};");
        }
        let doc = self.doc(s.span);
        if s.repr.packed {
            self.out.push_str("#pragma pack(push, 1)\n");
        }
        let _ = writeln!(self.out, "{doc}typedef {kw} {name} {{\n{body}}} {name};");
        if s.repr.packed {
            self.out.push_str("#pragma pack(pop)\n");
        }
        self.out.push('\n');
        Ok(name)
    }

    /// The C name of `#[repr(iN)]` enum `id`: a typedef of its tag type
    /// and a `#define` per variant.
    fn enumeration(&mut self, id: EnumId) -> Result<String, String> {
        let e = self
            .hir
            .enums
            .iter()
            .find(|e| e.id == id)
            .ok_or("an unknown enum")?
            .clone();
        let name = short_name(&e.name).to_owned();
        if self.enums.contains(&id) {
            return Ok(name);
        }
        let tag = e
            .repr
            .int
            .ok_or_else(|| format!("`{name}` has no `#[repr(i32)]`-like tag type"))?;
        if e.variants.iter().any(|v| v.payload_ty.is_some()) {
            return Err(format!(
                "`{name}` has variants with data, which C enums do not"
            ));
        }
        self.enums.push(id);
        let doc = self.doc(e.span);
        let _ = writeln!(self.out, "{doc}typedef {} {name};", prim(tag));
        let upper = snake_upper(&name);
        for v in &e.variants {
            let _ = writeln!(
                self.out,
                "#define {upper}_{} (({name}){})",
                snake_upper(&v.name),
                v.tag
            );
        }
        self.out.push('\n');
        Ok(name)
    }

    /// The `///` lines right above the item at `span` as a C comment.
    fn doc(&self, span: nabic_diagnostic::Span) -> String {
        let Some((_, text)) = self.sources.file(span.file) else {
            return String::new();
        };
        let start = usize::try_from(span.start).unwrap_or(0).min(text.len());
        let mut lines: Vec<&str> = Vec::new();
        let before = text[..start].rsplit_once('\n').map_or("", |(b, _)| b);
        for line in before.lines().rev() {
            let t = line.trim();
            if let Some(d) = t.strip_prefix("///") {
                lines.push(d.strip_prefix(' ').unwrap_or(d));
            } else if !t.starts_with("#[") {
                break;
            }
        }
        if lines.is_empty() {
            return String::new();
        }
        lines.reverse();
        let mut c = String::from("/**\n");
        for l in lines {
            let l = l.replace("*/", "* /");
            if l.is_empty() {
                c.push_str(" *\n");
            } else {
                let _ = writeln!(c, " * {l}");
            }
        }
        c.push_str(" */\n");
        c
    }
}

const fn prim(p: PrimTy) -> &'static str {
    match p {
        PrimTy::I8 => "int8_t",
        PrimTy::I16 => "int16_t",
        PrimTy::I32 => "int32_t",
        PrimTy::I64 => "int64_t",
        PrimTy::Isize => "ptrdiff_t",
        PrimTy::U8 => "uint8_t",
        PrimTy::U16 => "uint16_t",
        PrimTy::U32 | PrimTy::Char => "uint32_t",
        PrimTy::U64 => "uint64_t",
        PrimTy::Usize => "size_t",
        PrimTy::F32 => "float",
        PrimTy::F64 => "double",
        PrimTy::Bool => "bool",
        PrimTy::CChar => "char",
        // A C-ABI `str` is a NUL-terminated `char*`.
        PrimTy::Str => "const char *",
    }
}

/// `bare::ptr::CPtr` (an instance: `bare::ptr::CPtr__Struct231`) ->
/// `CPtr`.
fn short_name(full: &str) -> &str {
    let last = full.rsplit("::").next().unwrap_or(full);
    last.split("__").next().unwrap_or(last)
}

/// `TextAlign` -> `TEXT_ALIGN`.
fn snake_upper(s: &str) -> String {
    let mut out = String::new();
    let mut prev_lower = false;
    for c in s.chars() {
        if c.is_ascii_uppercase() && prev_lower {
            out.push('_');
        }
        prev_lower = c.is_ascii_lowercase() || c.is_ascii_digit();
        out.push(c.to_ascii_uppercase());
    }
    out
}
