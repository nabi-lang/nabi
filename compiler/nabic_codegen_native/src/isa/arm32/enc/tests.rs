#[test]
fn forms_encode_and_print_as_the_reference_tools() {
    let l = Listing {
        name: "f",
        code: &[],
        labels: Vec::new(),
        relocs: &[],
    };
    let cases = cases();
    assert_eq!(cases.len(), WANT.len());
    for (n, (i, (word, want))) in cases.iter().zip(WANT).enumerate() {
        assert_eq!(i.word, *word, "case {n}: {want}");
        let got = text(i.word, i.f, 4 * n as i64, &l);
        // The target's annotation names the function, not `.text`.
        let got = got.split(" <").next().unwrap_or_default();
        assert_eq!(got, want.split(" <").next().unwrap_or_default(), "case {n}");
    }
}

/// Text off records nothing; on, the listing shows labels, patched
/// branch targets, data words as bytes and relocations.
#[test]
fn listing_shows_labels_targets_data_and_relocations() {
    let code = |a: &mut Asm| {
        a.push(push(0x4ff0));
        a.push(bl());
        a.push(ls(Acc::Ldr, r(4), PC, 4));
        a.push(b(Cond::AL));
        a.push(word(0));
        a.push(b(Cond::NE));
        a.patch24(3, 0);
        a.patch24(5, -6);
    };
    let mut off = Asm::new(false);
    code(&mut off);
    let mut a = Asm::new(true);
    code(&mut a);
    assert_eq!(off.code, a.code);
    let mut obj = Obj::new(false, true, false);
    obj.arm = true;
    let g = obj.sym("g");
    let tls = obj.sym("tls");
    let relocs = [(4, RelKind::ArmCall, g), (16, RelKind::ArmTlsIe, tls)];
    let bytes: Vec<u8> = a.code.iter().flat_map(|w| w.to_le_bytes()).collect();
    let l = Listing {
        name: "f",
        code: &bytes,
        labels: vec![(4, 2)],
        relocs: &relocs,
    };
    assert!(off.lines(&l).is_empty());
    let lines = a.lines(&l);
    crate::asm::function(&mut obj, &l, &lines, crate::asm::Bytes::Words);
    let want = "
<f>:
       0: e92d4ff0     \tpush\t{r4, r5, r6, r7, r8, r9, r10, r11, lr}
.L2:
       4: ebfffffe     \tbl\t0x4 <.L2>
\t\t\t00000004:  R_ARM_CALL\tg
       8: e59f4004     \tldr\tr4, [pc, #0x4]
       c: ea000000     \tb\t0x14 <f+0x14>
      10: 00 00 00 00  \t.word\t0x00000000
\t\t\t00000010:  R_ARM_TLS_IE32\ttls
      14: 1afffffa     \tbne\t0x4 <.L2>
";
    assert_eq!(obj.asm.as_deref(), Some(want));
}
