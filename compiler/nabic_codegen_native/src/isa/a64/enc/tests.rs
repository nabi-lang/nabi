#[test]
fn bitmasks_decode_to_their_values() {
    for (v, bits) in [
        (0xffu64, 32),
        (0xffff, 32),
        (0x8000_0001, 32),
        (0x3ff, 64),
        (0x5555_5555_5555_5555, 64),
        (0xffff_ffff_ffff_fff0, 64),
        (0x0f0f_0f0f_0f0f_0f0f, 64),
    ] {
        let Bitmask(m) = bitmask(v, bits).expect("encodes");
        let got = decode_bitmask(m >> 12, (m >> 6) & 0x3f, m & 0x3f, bits == 64);
        assert_eq!(got, v, "{v:#x}");
    }
}
