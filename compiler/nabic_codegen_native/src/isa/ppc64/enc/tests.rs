#[test]
fn forms_encode_and_print_as_the_reference_tools() {
    let l = Listing {
        name: "f",
        code: &[],
        labels: Vec::new(),
        relocs: &[],
    };
    let cases = cases();
    assert_eq!(cases.len(), WANT.len());
    for (n, (i, (word, want))) in cases.iter().zip(WANT).enumerate() {
        assert_eq!(i.word(), *word, "case {n}: {want}");
        let got = text(i.word(), i.f, 4 * n as i64, &l);
        let got = got.split(" <").next().unwrap_or_default();
        assert_eq!(got, want.split(" <").next().unwrap_or_default(), "case {n}");
    }
}

/// Text off records nothing; on, branches patched later show their
/// final targets and labels, relocations their names and addends.
#[test]
fn listing_shows_labels_targets_and_relocations() {
    let mut a = Asm::new(false);
    a.push(blr());
    let l = Listing {
        name: "f",
        code: &[],
        labels: Vec::new(),
        relocs: &[],
    };
    assert!(a.lines(&l).is_empty());
    let mut obj = crate::obj::Obj::new(false, true, false);
    obj.ppc64 = true;
    let toc = obj.sym(".TOC.");
    let g = obj.sym("g");
    let mut a = Asm::new(true);
    a.push(addis(r(2), r(12), 0));
    a.push(addi(r(2), r(2), 0));
    let top = a.pos();
    a.push(bl());
    a.push(nop());
    a.push(bc(Cond::f(EQ), 0));
    a.push(b(0));
    a.push(blr());
    a.patch_bc(4, 8);
    a.patch_b(5, -12);
    let relocs = [
        (0, crate::obj::RelKind::PpcEntryHa, toc),
        (4, crate::obj::RelKind::PpcEntryLo, toc),
        (8, crate::obj::RelKind::PpcCall, g),
    ];
    let code: Vec<u8> = a.code.iter().flat_map(|w| w.to_le_bytes()).collect();
    let l = Listing {
        name: "f",
        code: &code,
        labels: vec![(4 * top as u32, 3), (24, 4)],
        relocs: &relocs,
    };
    let lines = a.lines(&l);
    crate::asm::function(&mut obj, &l, &lines, crate::asm::Bytes::EachWord);
    let want = "
<f>:
       0: 00 00 4c 3c  \taddis 2, 12, 0
\t\t0000000000000000:  R_PPC64_REL16_HA\t.TOC.
       4: 00 00 42 38  \taddi 2, 2, 0
\t\t0000000000000004:  R_PPC64_REL16_LO\t.TOC.+0x4
.L3:
       8: 01 00 00 48  \tbl 0x8 <.L3>
\t\t0000000000000008:  R_PPC64_REL24\tg
       c: 00 00 00 60  \tnop
      10: 08 00 82 40  \tbf\t2, 0x18 <.L4>
      14: f4 ff ff 4b  \tb 0x8 <.L3>
.L4:
      18: 20 00 80 4e  \tblr
";
    assert_eq!(obj.asm.as_deref(), Some(want));
}
